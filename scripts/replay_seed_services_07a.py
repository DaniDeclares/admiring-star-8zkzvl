#!/usr/bin/env python3
"""Replay-workspace-only prerequisite: the ten Production `services` rows referenced by 20261006233600.

The archived Production SQL 20261006233600_reconcile_verified_stripe_marketing_services_07a001_010_v2 upserts
dd_stripe_catalog_sync rows whose source_service_id values are Production `services` UUIDs. Those rows are runtime
data in Production (no migration source creates them), so a from-scratch replay cannot satisfy
dd_stripe_catalog_sync_source_service_id_fkey.

This script writes ONE extra migration file into the disposable replay workspace, versioned immediately before
20261006233600, that inserts only the identifying columns (id, sku, slug, name) of those ten rows. No price, status,
Stripe identifier or other business data is seeded; the foreign key is satisfied, never disabled. It fails closed:
  * the target archived migration must be present in the workspace;
  * every source_service_id UUID in that migration must be covered by the seed, and every seeded UUID must be used;
  * the seed slot version must not already exist.
Identifiers were verified read-only against Production on 2026-10-12 (id <-> sku <-> slug <-> name).
Usage: replay_seed_services_07a.py <replay-migrations-dir>
"""
import glob
import os
import re
import sys

TARGET_VERSION = "20261006233600"
SEED_VERSION = "20261006233599"
SEED_NAME = "replay_prerequisite_services_07a001_010"

# (id, sku, slug, name): verified against Production public.services
SEED = [
    ("4dd9d3a6-5e1c-4e89-8c4e-ab740c45c4fc", "DNI-07A-001", "d07-001", "Marketing Audit"),
    ("1e285297-4955-4736-bf99-2d3acd3408f6", "DNI-07A-002", "d07-002", "Marketing Strategy"),
    ("1b7b67cb-b0d0-4985-8f34-8379b375c160", "DNI-07A-003", "d07-003", "Campaign Planning"),
    ("6fec8d1b-1d5c-4a0a-916c-7cfdaaeef1de", "DNI-07A-004", "d07-004", "Content Calendar"),
    ("beff1846-df32-4ade-950e-022fd60f8e7b", "DNI-07A-005", "d07-005", "Social Media Management"),
    ("a7e373d4-f652-455c-9a96-1287e0c1d497", "DNI-07A-006", "d07-006", "Social Post Creation"),
    ("56987a25-c84f-4222-ab67-710ef6cf44a5", "DNI-07A-007", "d07-007", "Short-Form Content"),
    ("0921bbfe-c419-4806-aec8-00b3b834a148", "DNI-07A-008", "d07-008", "Email Marketing Setup"),
    ("845a7cd1-d0f8-4545-819a-ec67ba019a16", "DNI-07A-009", "d07-009", "Newsletter Production"),
    ("f2e7aa74-ae93-4b84-b6ce-dea4036cd993", "DNI-07A-010", "d07-010", "Local SEO Setup"),
]
UUID_RE = re.compile(r"'([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})'")


def referenced_uuids(sql):
    """UUIDs used as source_service_id values in the dd_stripe_catalog_sync upsert."""
    m = re.search(r"insert into public\.dd_stripe_catalog_sync\(.*?\)\s*values(.*?)on conflict", sql, re.S | re.I)
    if not m:
        raise SystemExit("dd_stripe_catalog_sync upsert not found in target migration; refusing to guess")
    return sorted(set(UUID_RE.findall(m.group(1))))


def seed_sql():
    rows = ",\n".join("  ('%s','%s','%s','%s')" % r for r in SEED)
    return (
        "-- REPLAY-WORKSPACE ONLY. Never committed to supabase/migrations; generated by scripts/replay_seed_services_07a.py.\n"
        "-- Identifier-only prerequisite rows (Production services runtime data) for 20261006233600's foreign key.\n"
        "insert into public.services(id, sku, slug, name) values\n%s\non conflict do nothing;\n" % rows
    )


def seed(directory):
    targets = glob.glob(os.path.join(directory, TARGET_VERSION + "_*.sql"))
    if len(targets) != 1:
        raise SystemExit("EXPECTED exactly one %s migration in the workspace, found %d" % (TARGET_VERSION, len(targets)))
    if glob.glob(os.path.join(directory, SEED_VERSION + "_*.sql")):
        raise SystemExit("seed slot %s already exists; refusing to overwrite" % SEED_VERSION)
    used = referenced_uuids(open(targets[0], encoding="utf8").read())
    seeded = sorted(r[0] for r in SEED)
    if used != seeded:
        raise SystemExit("seed does not match the migration's source_service_id values: missing=%s unused=%s" % (
            sorted(set(used) - set(seeded)), sorted(set(seeded) - set(used))))
    path = os.path.join(directory, "%s_%s.sql" % (SEED_VERSION, SEED_NAME))
    open(path, "w", encoding="utf8").write(seed_sql())
    print("wrote replay-only prerequisite %s (%d identifier-only services rows)" % (os.path.basename(path), len(SEED)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    seed(sys.argv[1])
