const assert = require('node:assert/strict');
const { classifyVendorEvidence, normalizeUrl } = require('./vendorOpportunityEvidence');
const base = { company: 'Example PM', url: 'https://example.com/vendors?utm_source=x', title: 'Vendor application for turnover cleaning', sourceVerified: true };
const first = classifyVendorEvidence(base);
assert.equal(first.status, 'OWNER_REVIEW');
assert.equal(first.feeFreeVerified, false);
assert.equal(first.route, 'DANI_AS_VENDOR');
assert.equal(classifyVendorEvidence(base, { [first.key]: first.evidence }).status, 'UNCHANGED');
assert.equal(classifyVendorEvidence({ ...base, body: 'Enroll via NetVendor' }).status, 'THIRD_PARTY_REVIEW');
assert.equal(classifyVendorEvidence({ ...base, title: 'Resident leasing application' }).status, 'IGNORE');
assert.equal(classifyVendorEvidence({ ...base, sourceVerified: false }).status, 'REVIEW_REQUIRED');
assert.equal(classifyVendorEvidence({ ...base, baseline: true }).status, 'BASELINED');
assert.equal(classifyVendorEvidence({ ...base, deadline: '2026-10-20' }, { [first.key]: first.evidence }).status, 'OWNER_REVIEW');
assert.equal(classifyVendorEvidence({ ...base, title: 'Request for proposal - janitorial' }).isSolicitation, true);
assert.equal(normalizeUrl(base.url), 'https://example.com/vendors');
assert.equal(normalizeUrl('https://user:password@example.com/vendors'), null);
console.log('vendor evidence checks passed');
